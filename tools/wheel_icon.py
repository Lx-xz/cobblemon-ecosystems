# Gera o ícone de casinha do botão "Habitat" no menu radial do Cobblemon (32x32, branco, no estilo dos ícones dele).
# Uso: python wheel_icon.py <saida.png> [previa.png]
import sys

from PIL import Image

HOUSE = """
................................
................................
................................
...............##...............
..............####....###.......
.............######...###.......
............###..###..###.......
...........###....###.###.......
..........###......######.......
.........###........#####.......
........###..........####.......
.......###............###.......
......###..............###......
.....###................###.....
....###..................###....
...######################.###...
......##..............##........
......##..............##........
......##..####........##........
......##..####...####.##........
......##..####...####.##........
......##..####...#..#.##........
......##.........#..#.##........
......##.........#..#.##........
......##.........#..#.##........
......##.........#..#.##........
......##.........#..#.##........
......##################........
......##################........
................................
................................
................................
"""

rows = [r for r in HOUSE.strip("\n").split("\n")]
im = Image.new("RGBA", (32, 32), (255, 255, 255, 0))
for y, row in enumerate(rows):
    for x, c in enumerate(row):
        if c == "#":
            im.putpixel((x, y), (255, 255, 255, 255))
im.save(sys.argv[1])
if len(sys.argv) > 2:
    bg = Image.new("RGBA", (32, 32), (60, 60, 60, 255))
    Image.alpha_composite(bg, im).resize((256, 256), Image.NEAREST).save(sys.argv[2])
