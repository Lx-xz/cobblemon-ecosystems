# Gera os ícones do botão "Coleta" no menu radial do Cobblemon (32x32, branco, no estilo do ícone de habitat):
# cesta com um ovo dentro (coleta ligada) e a mesma cesta cortada por um traço (coleta desligada).
# Uso: python farm_icon.py <ligado.png> <desligado.png> [previa.png]
import sys

from PIL import Image

BASKET = """
................................
................................
...........##########...........
.........###........###.........
........###..........###........
.......###....####....###.......
......###....######....###......
......##....########....##......
.....###....########....###.....
.....##....##########....##.....
.....##....##########....##.....
.....##....##########....##.....
.....##....##########....##.....
.....##....##########....##.....
.....##..................##.....
..############################..
..############################..
..############################..
................................
...####.####.####.####.####.#...
...####.####.####.####.####.#...
................................
....##.####.####.####.####.##...
....##.####.####.####.####.##...
................................
.....####.####.####.####.###....
.....####.####.####.####.###....
................................
......#####################.....
......#####################.....
................................
................................
"""


def basket():
    im = Image.new("RGBA", (32, 32), (255, 255, 255, 0))
    for y, row in enumerate(BASKET.strip("\n").split("\n")):
        for x, c in enumerate(row):
            if c == "#":
                im.putpixel((x, y), (255, 255, 255, 255))
    return im


def crossed(im):
    """Traço na diagonal (de cima à esquerda até embaixo à direita), com uma borda vazia para destacar."""
    im = im.copy()
    for y in range(1, 31):
        for x in range(1, 31):
            d = abs(x - y)
            if d <= 1:
                im.putpixel((x, y), (255, 255, 255, 255))
            elif d <= 3:
                im.putpixel((x, y), (255, 255, 255, 0))
    return im


on = basket()
off = crossed(on)
on.save(sys.argv[1])
off.save(sys.argv[2])
if len(sys.argv) > 3:
    bg = Image.new("RGBA", (72, 32), (60, 60, 60, 255))
    bg.alpha_composite(on, (0, 0))
    bg.alpha_composite(off, (40, 0))
    bg.resize((576, 256), Image.NEAREST).save(sys.argv[3])
